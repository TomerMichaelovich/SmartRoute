import { writeFileSync } from "fs";

/**
 * Regenerates src/infrastructure/prices/settlements-data.ts from the CBS settlements
 * list on data.gov.il. The chains' Stores files identify a branch's city by this
 * CBS code, and the app turns the shopper's reverse-geocoded city name into one.
 *
 * Usage: tsx scripts/prices/build-settlements.ts
 */

const RESOURCE_ID = "5c78e9fa-c2e2-4771-93ff-7f400a12f7ba";
const OUT = "src/infrastructure/prices/settlements-data.ts";

type CbsRecord = { סמל_ישוב: string; שם_ישוב: string; שם_ישוב_לועזי: string };

const clean = (s: string) => s.replace(/\s+/g, " ").trim();

// The CBS list writes some names with the parenthesised qualifier swapped or with
// typographic quirks; this keeps the published name and lets the matcher add variants.
async function main() {
  const url = `https://data.gov.il/api/3/action/datastore_search?resource_id=${RESOURCE_ID}&limit=5000`;
  const res = await fetch(url, { headers: { "user-agent": "NAVIO-settlements/0.1 (+https://navio.co.il)" } });
  if (!res.ok) throw new Error(`data.gov.il HTTP ${res.status}`);
  const records: CbsRecord[] = (await res.json()).result.records;

  const rows = records
    .map((r) => ({ code: Number(r.סמל_ישוב), he: clean(r.שם_ישוב), en: clean(r.שם_ישוב_לועזי) }))
    .filter((r) => r.code > 0 && r.he)
    .sort((a, b) => a.code - b.code);

  const body = rows.map((r) => `  [${r.code}, ${JSON.stringify(r.he)}, ${JSON.stringify(r.en)}],`).join("\n");
  writeFileSync(
    OUT,
    `// Generated by scripts/prices/build-settlements.ts from the CBS settlements list
// (data.gov.il resource ${RESOURCE_ID}). Do not edit by hand.
// [cbsCode, hebrewName, englishName]
export const SETTLEMENTS: ReadonlyArray<readonly [number, string, string]> = [
${body}
];
`,
  );
  console.log(`${rows.length} settlements -> ${OUT}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
